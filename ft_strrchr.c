#include <stddef.h>

char	*ft_strrchr(const char *s, int c)
{
	int	i;
	int	pos;

	i = 0;
	pos = -1;
	while (s[i])
	{
		if (s[i] == (char)c)
			pos = i;
		i++;
	}
	if ((char)c == '\0')
		return ((char *)&s[i]);
	else if (pos == -1)
		return (NULL);
	return ((char *)&s[pos]);
}
