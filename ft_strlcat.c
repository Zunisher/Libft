#include <stddef.h>

size_t	ft_strlcat(char *dst, const char *src, size_t n)
{
	size_t	i;
	size_t	j;
	size_t	k;

	k = 0;
	i = 0;
	j = 0;
	while (j < n && dst[j])
		j++;
	while (src[k])
		k++;
	if (n == 0)
		return (k);
	else if (n == j)
		return (k + n);
	while (j + i < n - 1 && src[i])
	{
		dst[j + i] = src[i];
		i++;
	}
	dst[j + i] = '\0';
	return (j + k);
}
